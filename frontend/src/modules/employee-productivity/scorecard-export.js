export async function renderScorecardPdf(p) {
  const L = labelsOf(p);
  const logo = await loadLogo();
  const W = 595.28, H = 841.89, M = 40, CW = W - 2 * M, FOOT = 58;
  const pages = [];
  let s = '';
  const f = (n) => Number(n.toFixed(2));
  const fill = (x, y, w, h, col) => { s += `${col} rg\n${f(x)} ${f(y)} ${f(w)} ${f(h)} re f\n`; };
  const box = (x, y, w, h, col, lw = 0.6) => { s += `${col} RG\n${lw} w\n${f(x)} ${f(y)} ${f(w)} ${f(h)} re S\n`; };
  const line = (x1, y1, x2, y2, col, lw = 0.5) => { s += `${col} RG\n${lw} w\n${f(x1)} ${f(y1)} m ${f(x2)} ${f(y2)} l S\n`; };
  const text = (x, y, size, str, col, bold) => { s += `${col} rg\nBT /${bold ? 'F2' : 'F1'} ${size} Tf ${f(x)} ${f(y)} Td (${pdfEscape(sanitize(str))}) Tj ET\n`; };
  const textR = (xRight, y, size, str, col, bold) => text(xRight - advance(str, size, bold), y, size, str, col, bold);
  const section = (yy, label) => {
    fill(M, yy - 1.5, 3, 10, C.accent);
    text(M + 9, yy, TYPE.section, fit(label.toUpperCase(), CW - 9, TYPE.section, true), C.ink, true);
    line(M, yy - 7, M + CW, yy - 7, C.border, 0.6);
    return yy - 22;
  };

  // ── Brand header — the same on every page: logo, wordmark and tagline on
  // the left; report ID and the generated stamp on the right; accent rule. ──
  const headerValue = (re) => (p.header.find(([k]) => re.test(k)) || [])[1];
  const generatedAt = headerValue(/generated at/i);
  const generatedBy = headerValue(/generated by/i);
  const stamp = [generatedAt && `Generated ${generatedAt}`, generatedBy && `by ${generatedBy}`].filter(Boolean).join(' ');
  const brandHeader = () => {
    const top = H - M;
    const markH = 26;
    const markW = logo ? (logo.w / logo.h) * markH : 0;
    if (logo) s += `q ${f(markW)} 0 0 ${markH} ${M} ${f(top - markH)} cm /Im1 Do Q\n`;
    const wx = M + (logo ? markW + 8 : 0);
    text(wx, top - 12, TYPE.brand, 'DRISHYAM', C.ink, true);
    text(wx, top - 23, TYPE.small, L.tagline, C.slate, false);
    const rightW = CW - (wx - M) - advance(L.tagline, TYPE.small, false) - 16;
    textR(M + CW, top - 7, TYPE.label, 'REPORT ID', C.gray, true);
    textR(M + CW, top - 17, TYPE.value, fit(p.reportId, rightW, TYPE.value, true), C.dark, true);
    if (stamp) textR(M + CW, top - 27, TYPE.small, fit(stamp, rightW, TYPE.small, false), C.slate, false);
    const ruleY = top - markH - 12;
    fill(M, ruleY, CW, 2.2, C.accent);
    return ruleY;
  };

  // ── Page 1: title and subtitle ──
  let y = brandHeader() - 30;
  const titleLines = wrap(p.title, CW, TYPE.title, true, 2);
  titleLines.forEach((ln, i) => text(M, y - i * 22, TYPE.title, ln, C.ink, true));
  y -= (titleLines.length - 1) * 22 + 15;
  text(M, y, TYPE.value, fit(L.subtitle, CW, TYPE.value, false), C.slate, false);
  y -= 18;

  // ── Report details, two columns of label over value ──
  const details = p.header.filter(([k]) => !/generated at/i.test(k));
  const detRowH = 27, detPad = 10;
  const detH = Math.ceil(details.length / 2) * detRowH + detPad * 2 - 6;
  fill(M, y - detH, CW, detH, C.panel);
  box(M, y - detH, CW, detH, C.border, 0.6);
  const halfW = (CW - detPad * 2) / 2;
  details.forEach(([k, v], i) => {
    const x = M + detPad + (i % 2) * halfW;
    const yy = y - detPad - 7 - Math.floor(i / 2) * detRowH;
    text(x, yy, TYPE.label, fit(String(k).toUpperCase(), halfW - 14, TYPE.label, true), C.slate, true);
    const vs = fitSize(v, halfW - 14, TYPE.value, TYPE.body, false);
    text(x, yy - 11, vs, fit(v, halfW - 14, vs, false), C.ink, false);
  });
  y -= detH + 24;

  // ── Policy — three per row, label over value; values wrap to two lines ──
  if (p.policy?.length) {
    y = section(y, L.policy);
    const per = 3, pcW = CW / per, polRowH = 36;
    p.policy.forEach(([k, v], i) => {
      const x = M + (i % per) * pcW;
      const yy = y - Math.floor(i / per) * polRowH;
      text(x, yy, TYPE.label, fit(String(k).toUpperCase(), pcW - 12, TYPE.label, true), C.slate, true);
      wrap(v, pcW - 12, TYPE.text, false, 2).forEach((ln, li) => text(x, yy - 11 - li * 10, TYPE.text, ln, C.ink, false));
    });
    y -= Math.ceil(p.policy.length / per) * polRowH + 8;
  }

  // ── Summary tiles — up to four in a row ──
  if (p.kpis?.length) {
    y = section(y, L.summary);
    const per = Math.min(4, p.kpis.length), gap = 8;
    const tileW = (CW - gap * (per - 1)) / per, tileH = 72;
    p.kpis.forEach((k, i) => {
      const x = M + (i % per) * (tileW + gap);
      const top = y + 8 - Math.floor(i / per) * (tileH + gap);
      box(x, top - tileH, tileW, tileH, C.border, 0.6);
      fill(x, top - tileH, 2.5, tileH, C.accent);
      const inner = tileW - 16;
      wrap(String(k.label).toUpperCase(), inner, TYPE.label, true, 2)
        .forEach((ln, li) => text(x + 10, top - 12 - li * 8.5, TYPE.label, ln, C.slate, true));
      const vs = fitSize(k.value, inner, TYPE.brand, 10, true);
      text(x + 10, top - 39, vs, fit(k.value, inner, vs, true), C.ink, true);
      wrap(k.note, inner, TYPE.small, false, 2).forEach((ln, li) => text(x + 10, top - 52 - li * 8.5, TYPE.small, ln, C.gray, false));
    });
    y -= Math.ceil(p.kpis.length / per) * (tileH + gap) + 14;
  }

  // ── Pages 2+: the same brand header, then the title marked "continued" ──
  const newPage = () => {
    pages.push(s);
    s = '';
    y = brandHeader() - 20;
    text(M, y, TYPE.value, fit(`${p.title}  (continued)`, CW, TYPE.value, true), C.ink, true);
    y -= 24;
  };

  // ── Tables ──
  const tables = tablesOf(p, L);
  const rowH = 16, size = TYPE.body, headSize = TYPE.label, headLine = 8, pad = 5;

  tables.forEach((t, ti) => {
    if (ti > 0) y -= 24;
    if (y - (22 + 34 + rowH * 2) < FOOT) newPage();
    y = section(y, t.title);

    // Widths in points. Each column needs room for its widest cell and for the
    // longest WORD of its header (headers wrap, so a long title need not widen
    // its column, but no single word may be cut). Spare width is shared in
    // proportion to that need; if the needs overflow the page, all shrink.
    const need = t.columns.map((c, ci) => {
      const head = Math.max(...String(c).toUpperCase().split(' ').map((w) => advance(w, headSize, true)));
      const body = Math.max(0, ...t.rows.map((r) => advance(r[ci], size, ci === 0 || !!TONE[String(r[ci]).trim().toLowerCase()])));
      return Math.min(Math.max(head, body, 18), CW * 0.3) + pad * 2;
    });
    const needTot = need.reduce((a, b) => a + b, 0);
    const colW = need.map((w) => w * (CW / needTot));
    const colX = [];
    let cx = M;
    colW.forEach((w) => { colX.push(cx); cx += w; });
    const numeric = t.columns.map((_, ci) => t.rows.length > 0
      && t.rows.every((r) => isNumeric(r[ci]) || r[ci] === '' || r[ci] === '-'));
    const cell = (ci, yy, sz, str, col, bold) => (numeric[ci]
      ? textR(colX[ci] + colW[ci] - pad, yy, sz, str, col, bold)
      : text(colX[ci] + pad, yy, sz, str, col, bold));

    // Header titles wrap to up to three lines; the row is as tall as the
    // tallest, and every title is centred in it vertically.
    const headLines = t.columns.map((c, ci) => wrap(String(c).toUpperCase(), colW[ci] - pad * 2, headSize, true, 3));
    const headH = Math.max(...headLines.map((l) => l.length)) * headLine + 10;
    const headerRow = () => {
      fill(M, y - headH, CW, headH, C.head);
      headLines.forEach((lines, ci) => {
        const top = y - (headH - lines.length * headLine) / 2 - headSize;
        lines.forEach((ln, li) => cell(ci, top - li * headLine + 0.5, headSize, ln, C.white, true));
      });
      y -= headH;
    };

    headerRow();
    t.rows.forEach((r, ri) => {
      if (y - rowH < FOOT) {
        newPage();
        y = section(y, `${t.title} (continued)`);
        headerRow();
      }
      if (ri % 2 === 1) fill(M, y - rowH, CW, rowH, C.zebra);
      if (t.heat) {
        t.columns.forEach((_, ci) => {
          const hf = heatFill(t.heat, r[ci]);
          if (hf) fill(colX[ci] + 1, y - rowH + 1, colW[ci] - 2, rowH - 2, hf);
        });
      }
      t.columns.forEach((_, ci) => {
        const tone = TONE[String(r[ci]).trim().toLowerCase()];
        const bold = ci === 0 || !!tone;
        cell(ci, y - rowH + 5.2, size, fit(r[ci], colW[ci] - pad * 2, size, bold), tone || (ci === 0 ? C.ink : C.dark), bold);
      });
      y -= rowH;
      line(M, y, M + CW, y, C.border, 0.35);
    });
  });
  pages.push(s);

  // ── Footer on every page, now that the count is known ──
  const countLine = p.countLine || `${tables[0]?.rows.length ?? 0} ${L.rowNoun}`;
  const bodies = pages.map((body, i) => {
    s = body;
    line(M, 42, M + CW, 42, C.border, 0.6);
    text(M, 30, TYPE.small, fit(L.footer, CW * 0.75, TYPE.small, false), C.gray, false);
    text(M, 21, TYPE.small, fit(`${p.reportId}  -  ${countLine}`, CW * 0.75, TYPE.small, false), C.gray, false);
    textR(M + CW, 30, TYPE.text, `Page ${i + 1} of ${pages.length}`, C.slateDark, true);
    return s;
  });

  // Objects: 1 catalog · 2 pages · 3/4 fonts · 5 logo (or an empty
  // placeholder) · then (page, content) pairs · then the document info
  // (title, author) a PDF viewer shows. Written as bytes, because the logo
  // stream is binary.
  const enc = new TextEncoder();
  const kids = bodies.map((_, i) => `${6 + i * 2} 0 R`).join(' ');
  const objs = [
    '<</Type/Catalog/Pages 2 0 R>>',
    `<</Type/Pages/Kids[${kids}]/Count ${bodies.length}>>`,
    '<</Type/Font/Subtype/Type1/BaseFont/Helvetica/Encoding/WinAnsiEncoding>>',
    '<</Type/Font/Subtype/Type1/BaseFont/Helvetica-Bold/Encoding/WinAnsiEncoding>>',
    logo
      ? [`<</Type/XObject/Subtype/Image/Width ${logo.w}/Height ${logo.h}/ColorSpace/DeviceRGB/BitsPerComponent 8/Filter/DCTDecode/Length ${logo.bytes.length}>>\nstream\n`, logo.bytes, '\nendstream']
      : '<<>>',
  ];
  const xobj = logo ? '/XObject<</Im1 5 0 R>>' : '';
  bodies.forEach((body, i) => {
    objs.push(`<</Type/Page/Parent 2 0 R/MediaBox[0 0 ${W} ${H}]/Resources<</Font<</F1 3 0 R/F2 4 0 R>>${xobj}>>/Contents ${7 + i * 2} 0 R>>`);
    objs.push(`<</Length ${body.length}>>\nstream\n${body}endstream`);
  });
  const str = (v) => `(${pdfEscape(sanitize(v))})`;
  const created = istNow().stamp.replace('-', '');
  objs.push(`<</Title${str(p.title)}/Author(Drishyam)/Subject${str(`Report ID ${p.reportId}`)}`
    + `/Creator(Drishyam Activity Monitoring)/Producer(Drishyam)/CreationDate(D:${created}00+05'30')>>`);
  const info = objs.length;

  const chunks = [];
  let len = 0;
  const put = (part) => { const b = typeof part === 'string' ? enc.encode(part) : part; chunks.push(b); len += b.length; };
  put('%PDF-1.4\n');
  const offsets = [];
  objs.forEach((o, i) => {
    offsets.push(len);
    put(`${i + 1} 0 obj\n`);
    (Array.isArray(o) ? o : [o]).forEach(put);
    put('\nendobj\n');
  });
  const xref = len;
  put(`xref\n0 ${objs.length + 1}\n0000000000 65535 f \n`);
  offsets.forEach((o) => put(`${String(o).padStart(10, '0')} 00000 n \n`));
  put(`trailer\n<</Size ${objs.length + 1}/Root 1 0 R/Info ${info} 0 R>>\nstartxref\n${xref}\n%%EOF`);

  return new Blob(chunks, { type: 'application/pdf' });
}
