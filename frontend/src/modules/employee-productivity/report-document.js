// ─────────────────────────────────────────────────────────────────────────────
// Report document — the one way an Activity Monitoring page exports a file.
//
// Every page (retail, campus, school, hostel, hospitality, bank) describes its
// export as a title, a few detail lines, optional KPI tiles and one or more
// tables; this turns that into the scorecard payload and hands it to the
// branded writers in scorecard-export.js. So every PDF carries the Drishyam
// logo and header on every page, a report ID, a details box and "Page n of N";
// every workbook opens on a Summary tab with the logo; every CSV opens with the
// same header block. A page never writes its own CSV / PDF by hand.
// ─────────────────────────────────────────────────────────────────────────────

import { useAuthStore } from '@/core/store/authStore';
import {
  download, istNow, renderScorecardCsv, renderScorecardPdf, renderScorecardXlsx,
} from './scorecard-export';

const slugify = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'report';

// The signed-in user, as the report's "Generated By".
function currentUser() {
  const user = useAuthStore.getState().user;
  return user?.name || user?.email || 'Drishyam user';
}

/**
 * Build a branded report payload.
 * @param {{
 *   title: string,                       // "Weekly operations summary"
 *   code?: string,                       // report-ID code: RPT-<code>-<stamp>
 *   subtitle?: string,                   // line under the title
 *   details?: [string, string][],        // "Organisation", "Period", "Scope"…
 *   policy?: [string, string][],         // thresholds / filters the numbers used
 *   kpis?: { label: string, value: string, note?: string }[],
 *   tables: { title: string, columns: string[], rows: (string|number)[][], sheet?: string, heat?: object }[],
 *   rowNoun?: string, countLine?: string, footer?: string, filename?: string,
 * }} o
 */
export function reportDocument(o) {
  const now = istNow();
  const code = (o.code || 'AM').toUpperCase();
  return {
    title: o.title,
    reportId: `RPT-${code}-${now.stamp}`,
    header: [
      ['Report Type', o.title],
      ...(o.details || []).filter(([, v]) => v != null && v !== ''),
      ['Generated At', now.label],
      ['Generated By', currentUser()],
    ],
    policy: o.policy || [],
    kpis: (o.kpis || []).map((k) => ({ ...k, value: String(k.value), note: k.note || '' })),
    tables: o.tables.map((t) => ({ ...t, rows: t.rows.map((r) => r.map((v) => (v == null ? '' : v))) })),
    labels: {
      subtitle: o.subtitle || 'Drishyam Activity Monitoring',
      footer: o.footer || 'Confidential - generated by Drishyam Activity Monitoring for internal use.',
      rowNoun: o.rowNoun || 'rows',
    },
    countLine: o.countLine,
    filename: `${o.filename || slugify(o.title)}_${now.stamp}`,
  };
}

// 'PDF' | 'Excel' | 'CSV' (the campus button group) or 'pdf' | 'xlsx' | 'csv'.
const FORMAT = { pdf: 'pdf', excel: 'xlsx', xlsx: 'xlsx', xls: 'xlsx', csv: 'csv' };
const RENDER = { pdf: renderScorecardPdf, xlsx: renderScorecardXlsx, csv: renderScorecardCsv };

/** Render a report document in `format` and download it. Resolves to the filename. */
export async function exportReportDocument(doc, format) {
  const ext = FORMAT[String(format).toLowerCase()] || 'pdf';
  const payload = doc.reportId ? doc : reportDocument(doc);
  const filename = `${payload.filename}.${ext}`;
  download(await RENDER[ext](payload), filename);
  return filename;
}
