// ─────────────────────────────────────────────────────────────────────────────
// Camera Status export — one report, three formats, two ways to deliver it.
//
// The page builds ONE report object (`buildHealthReport`) and every format and
// both delivery routes read from it, so the PDF a manager opens, the CSV an
// analyst pivots and the JSON a script parses can never disagree about what
// the estate looked like at that moment.
//
//   PDF   the branded A4 document, written by the shared report writer the
//         Reports hub and the Event Log use (logo header, summary tiles,
//         zebra table, "Page n of N"), so a status report handed to a client
//         looks like every other Drishyam export.
//   CSV   the chosen columns as plain rows, exactly as the table shows them.
//         Deliberately NOT the branded CSV the scorecard writes: this file's
//         job is to open in a spreadsheet with its header on row 1.
//   JSON  the whole per-camera record, not just the chosen columns. A machine
//         reader cannot ask for the field someone forgot to tick, and raw
//         numbers (bitrateBps, delayMs) beat the formatted strings the other
//         two formats carry.
//
// Delivery is download or email. Email posts the file the browser just built
// to the notifications mailer, which already owns the SMTP account and the
// recipient list; a deployment whose API predates that route falls back to a
// download plus a pre-addressed draft rather than losing the report.
// ─────────────────────────────────────────────────────────────────────────────

import { cameraHealthService } from '@/core/services/cameraHealth';
import { istNow, renderScorecardPdf } from '@/modules/employee-productivity/scorecard-export';
import { COLUMNS, csvValue } from './health-columns';
import {
  bucketMeta,
  bucketOf,
  engineState,
  isStreaming,
} from './health-vocabulary';

export const EXPORT_FORMATS = [
  {
    id: 'pdf', label: 'PDF', ext: 'pdf', mime: 'application/pdf',
    hint: 'Branded A4 document — logo header, summary metrics, paginated table',
  },
  {
    id: 'csv', label: 'CSV', ext: 'csv', mime: 'text/csv;charset=utf-8',
    hint: 'The chosen columns as plain rows, for Excel or Sheets',
  },
  {
    id: 'json', label: 'JSON', ext: 'json', mime: 'application/json',
    hint: 'Every field per camera with raw numbers, for scripts and dashboards',
  },
];

const REPORT_TITLE = 'Camera Status Report';

const fmtDelay = (ms) => (ms == null ? '—' : `${Math.round(ms)} ms`);

const pct = (part, whole) => (whole ? `${Math.round((part / whole) * 100)}% of total` : 'No cameras');

/**
 * The numbers the report leads with, computed from the rows BEING EXPORTED
 * rather than taken from the page's own summary strip. An export scoped to one
 * site must not open with the whole estate's totals — the summary and the
 * table beneath it have to describe the same cameras.
 *
 * Average delay covers only the cameras actually sending video, the same rule
 * the page's strip uses: folding the silent ones in as 0 ms would flatter an
 * estate in which half the cameras are down.
 */
export function summarizeRows(rows) {
  const count = (bucket) => rows.filter((c) => bucketOf(c) === bucket).length;
  const streaming = rows.filter(isStreaming);
  const totalDelay = streaming.reduce((sum, c) => sum + (Number(c.jitterMs) || 0), 0);
  return {
    total: rows.length,
    online: count('online'),
    offline: count('offline'),
    unstable: count('unstable'),
    needsSetup: count('setup'),
    streaming: streaming.length,
    avgDelayMs: streaming.length ? totalDelay / streaming.length : null,
  };
}

/**
 * Assemble the report. Pure — the page passes in the rows it is showing and
 * the filters that produced them.
 *
 * @param {object}   o
 * @param {object[]} o.rows        the cameras to export, in table order
 * @param {string[]} o.columnIds   the chosen columns, for the PDF and CSV
 * @param {number}   o.total       cameras on the page before filtering
 * @param {string}   o.scopeLabel  what this export covers, in words
 * @param {[string, string][]} o.filters  the active filters, label and value
 * @param {string}   o.generatedBy who pressed the button
 */
export function buildHealthReport({
  rows, columnIds, total, scopeLabel, filters = [], generatedBy = 'Drishyam user',
}) {
  const now = istNow();
  const summary = summarizeRows(rows);
  const chosen = COLUMNS.filter((c) => columnIds.includes(c.id));

  return {
    title: REPORT_TITLE,
    reportId: `RPT-CHS-${now.stamp}`,
    header: [
      ['Report Type', REPORT_TITLE],
      ['Scope', scopeLabel],
      ['Cameras', total > rows.length ? `${rows.length} of ${total} cameras` : `${rows.length} cameras`],
      ['Generated At', now.label],
      ['Generated By', generatedBy],
    ],
    // The writer prints `policy` as the label-over-value block under the
    // details box. Here that block is what the numbers were narrowed by, so a
    // reader can tell a healthy estate from a narrow query.
    policy: filters.length ? filters : [['Filters', 'None — the whole estate']],
    kpis: [
      { label: 'Total Cameras', value: String(summary.total), note: `${summary.streaming} streaming` },
      { label: 'Online', value: String(summary.online), note: pct(summary.online, summary.total) },
      {
        label: 'Offline',
        value: String(summary.offline),
        note: summary.offline ? 'Need attention' : 'None down',
      },
      {
        label: 'Average Delay',
        value: fmtDelay(summary.avgDelayMs),
        note: summary.streaming ? `Across ${summary.streaming} streaming` : 'No cameras streaming',
      },
    ],
    tables: [{
      title: 'Cameras',
      columns: chosen.map((c) => c.label),
      rows: rows.map((camera) => chosen.map((c) => csvValue(camera, c.id))),
    }],
    labels: {
      subtitle: 'Live connectivity, delay and stream health across every camera.',
      tagline: 'AI VIDEO ANALYTICS  -  CAMERA HEALTH',
      policy: 'Applied filters',
      summary: 'Estate summary',
      footer: 'Exported from Drishyam Camera Status.',
      rowNoun: 'cameras',
    },
    filename: `camera-status_${now.stamp}`,
    // Not read by the PDF writer — the CSV and JSON renderers' source of truth,
    // and what the email body quotes.
    source: { rows, columnIds, summary, filters, scopeLabel, generatedAt: now.label, generatedBy },
  };
}

// ── CSV ──────────────────────────────────────────────────────────────────────
export function renderHealthCsv(report) {
  const { rows, columnIds } = report.source;
  const chosen = COLUMNS.filter((c) => columnIds.includes(c.id));
  const escape = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  const csv = [
    chosen.map((c) => escape(c.label)).join(','),
    ...rows.map((camera) => chosen.map((c) => escape(csvValue(camera, c.id))).join(',')),
  ].join('\r\n');
  return new Blob([csv], { type: 'text/csv;charset=utf-8' });
}

// ── JSON ─────────────────────────────────────────────────────────────────────
/** One camera as data: raw numbers, and null — never 0 — where there is no reading. */
function jsonCamera(camera) {
  const num = (v) => (v == null || v === '' || Number.isNaN(Number(v)) ? null : Number(v));
  const bucket = bucketOf(camera);
  return {
    id: camera.id ?? null,
    name: camera.name || null,
    streamId: camera.monitorId || null,
    site: camera.siteName || null,
    siteId: camera.siteId || null,
    group: camera.groupName || null,
    groupId: camera.groupId || null,
    status: bucketMeta(bucket).label,
    statusId: bucket,
    engineState: camera.status || 'unknown',
    engineHeadline: engineState(camera.status).headline,
    streaming: isStreaming(camera),
    delayMs: isStreaming(camera) ? num(camera.jitterMs) : null,
    bitrateBps: num(camera.bpsIn ?? camera.meanBps),
    lastUpdate: camera.lastUpdate || null,
    viewers: num(camera.readers),
    errorRate: num(camera.fieRate),
    drops24h: num(camera.flapCount),
    codec: camera.codec || null,
    resolution: camera.resolution || null,
    uptimeSec: num(camera.readSinceSec),
  };
}

export function renderHealthJson(report) {
  const { rows, summary, filters, scopeLabel, generatedAt, generatedBy } = report.source;
  const body = {
    report: {
      id: report.reportId,
      title: report.title,
      scope: scopeLabel,
      generatedAt,
      generatedBy,
      filters: Object.fromEntries(filters),
      cameraCount: rows.length,
    },
    summary,
    cameras: rows.map(jsonCamera),
  };
  return new Blob([JSON.stringify(body, null, 2)], { type: 'application/json' });
}

// ── Rendering and delivery ───────────────────────────────────────────────────
const RENDER = { pdf: renderScorecardPdf, csv: renderHealthCsv, json: renderHealthJson };

const formatMeta = (format) => EXPORT_FORMATS.find((f) => f.id === format) || EXPORT_FORMATS[0];

/** The report as a file: `{ blob, filename, mime }`. */
export async function renderHealthReport(report, format) {
  const meta = formatMeta(format);
  const blob = await RENDER[meta.id](report);
  return { blob, filename: `${report.filename}.${meta.ext}`, mime: meta.mime };
}

function saveFile(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  // Revoking on a later turn, not on this one. The browser reads the blob
  // asynchronously after the click, and dropping the URL synchronously races
  // that read — which truncated a 2600-camera export to its first few rows.
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}

/** Build the file and hand it to the browser. */
export async function downloadHealthReport(report, format) {
  const { blob, filename } = await renderHealthReport(report, format);
  saveFile(blob, filename);
  return { filename };
}

async function toBase64(blob) {
  const bytes = new Uint8Array(await blob.arrayBuffer());
  let binary = '';
  // Chunked: String.fromCharCode(...bytes) overruns the argument limit on a
  // PDF of any real size.
  for (let i = 0; i < bytes.length; i += 0x8000) {
    binary += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
  }
  return btoa(binary);
}

const mailSubject = (report) => `${report.title} - ${report.source.scopeLabel} (${report.reportId})`;

function mailBody(report, filename) {
  const { summary, generatedAt, scopeLabel } = report.source;
  return [
    'Hi,',
    '',
    `Attached is the ${report.title} for ${scopeLabel}, generated ${generatedAt}.`,
    '',
    `Total cameras: ${summary.total}`,
    `Online: ${summary.online}`,
    `Offline: ${summary.offline}`,
    `Average delay: ${fmtDelay(summary.avgDelayMs)}`,
    '',
    `Report ID: ${report.reportId}`,
    `File: ${filename}`,
  ].join('\n');
}

/** Statuses that mean "this API has no mail route", not "the send failed". */
const NO_ROUTE = [404, 405, 501];

/**
 * Email the report to `recipients`.
 *
 * Resolves `{ via: 'server' }` when the mailer took it, or `{ via: 'draft' }`
 * when this deployment has no mail route and the file was downloaded with a
 * pre-addressed draft opened instead. A browser cannot attach a file to a
 * mailto: URL, so on that path the caller has to tell the operator to attach
 * it themselves. A send that fails for any other reason throws — a 500 is a
 * problem to report, not a reason to quietly change what the button did.
 */
export async function emailHealthReport(report, format, recipients) {
  const { blob, filename, mime } = await renderHealthReport(report, format);

  try {
    await cameraHealthService.emailReport({
      recipients,
      subject: mailSubject(report),
      message: mailBody(report, filename),
      reportId: report.reportId,
      summary: report.source.summary,
      attachment: { filename, mime, base64: await toBase64(blob) },
    });
    return { via: 'server', filename };
  } catch (err) {
    const status = err?.response?.status;
    if (status && !NO_ROUTE.includes(status)) throw err;

    saveFile(blob, filename);
    const link = document.createElement('a');
    link.href = `mailto:${recipients.map(encodeURIComponent).join(',')}`
      + `?subject=${encodeURIComponent(mailSubject(report))}`
      + `&body=${encodeURIComponent(mailBody(report, filename))}`;
    link.click();
    return { via: 'draft', filename };
  }
}
